export const stripOpsStatus = (sheetKey: string) =>
  String(sheetKey || '').replace(/#(?:DONE|PEND)$/i, '')

export const opsStatusOf = (sheetKey: string): OpsStatus => {
  const key = String(sheetKey || '').toUpperCase()
  if (key.endsWith('#DONE')) return 'done'
  if (key.endsWith('#PEND')) return 'pending'
  return 'active'
}

export const opsPrimaryType = (base: OpsBase): OpsType | null => OPS_PRIMARY_TYPE[base] || null

export const opsTypesOf = (base: OpsBase): OpsType[] =>
  OPS_TYPES_BY_BASE[base]?.slice() || []

export const opsDeptsFor = (base: OpsBase, type?: OpsType | null): OpsDept[] =>
  (type && OPS_DEPTS_BY_TYPE[type] ? OPS_DEPTS_BY_TYPE[type] : OPS_DEPTS_BY_BASE[base]).slice()

export function opsLeafKey(base: OpsBase, mode: OpsMode, type: OpsType | null | undefined, dept: OpsDept): string {
  const primary = opsPrimaryType(base)
  if (type && type !== primary) return `${base}::${mode}::${type}::${dept}`
  return `${base}::${mode}::${dept}`
}

export function opsStatusKey(leafKey: string, status: OpsStatus): string {
  const leaf = stripOpsStatus(leafKey)
  if (status === 'done') return `${leaf}#DONE`
  if (status === 'pending') return `${leaf}#PEND`
  return leaf
}

// Parse "BASE::MODE::DEPT", "BASE::MODE::TYPE::DEPT", plus #PEND/#DONE.
export function parseOpsKey(sheetKey: string): {
  base: OpsBase
  mode: OpsMode
  type: OpsType | null
  dept: OpsDept
  status: OpsStatus
} | null {
  const status = opsStatusOf(sheetKey)
  const parts = stripOpsStatus(sheetKey).split('::')
  if (![3, 4].includes(parts.length)) return null
  const [baseRaw, modeRaw] = parts
  if (!['EFA', 'FCF', 'DO', 'DUP', 'D2D'].includes(baseRaw)) return null
  if (!['FCL', 'LCL', 'AIR'].includes(modeRaw)) return null
  const base = baseRaw as OpsBase
  const mode = modeRaw as OpsMode
  const type = parts.length === 4 ? parts[2] as OpsType : opsPrimaryType(base)
  const dept = (parts.length === 4 ? parts[3] : parts[2]) as OpsDept
  const allowedTypes = OPS_TYPES_BY_BASE[base]
  if (allowedTypes && type && !allowedTypes.includes(type)) return null
  if (!allowedTypes && type) return null
  return { base, mode, type, dept, status }
}
