const hiddenOpsColumns = (base: OpsBase, mode: OpsMode, dept: OpsDept): Set<number> => {
  if ((base === 'EFA' || base === 'FCF') && dept === 'ECD') {
    if (base === 'FCF') {
      if (mode === 'FCL') return new Set([28, 29, 30, 31])
      if (mode === 'LCL') return new Set([28, 29, 30, 31, 34, 35, 36, 44])
      return new Set([30, 31])
    }
    if (mode === 'FCL') return new Set([30, 31, 34])
    if (mode === 'LCL') return new Set([30, 31, 35, 36, 44])
    return new Set([30, 31])
  }
  if (base === 'EFA' && dept === 'CCD' && mode === 'FCL') return new Set([30])
  if (base === 'DO' && dept === 'ICD') {
    if (mode === 'FCL') return new Set([20])
    if (mode === 'LCL') return new Set([24, 25, 34])
  }
  if (base === 'DO' && dept === 'FCD' && mode === 'LCL') return new Set([19, 20])
  return new Set()
}

const opsHeaderName = (base: OpsBase, mode: OpsMode, dept: OpsDept, index: number, raw: string): string => {
  if (base === 'EFA') {
    if (mode === 'LCL' && dept === 'ECD') {
      if (index === 11) return 'CARRIER'
      if (index === 21) return 'CFS CUTOFF DATE'
    }
    if (mode === 'FCL' && dept === 'ECD' && index === 32) return 'SI READINESS'
  } else if (base === 'FCF') {
    if (dept === 'ECD') {
      if (index === 32) return 'SI READINESS'
      if (mode === 'LCL' && index === 11) return 'CARRIER'
    }
  } else if (base === 'DO') {
    if (dept === 'ICD') {
      if (mode === 'FCL' && index === 19) return 'CONTAINER/SEAL NO#'
      if (mode === 'LCL' && index === 10) return 'CARRIER'
    } else if (dept === 'FCD' && mode === 'LCL' && index === 10) {
      return 'CARRIER'
    }
  }
  return raw === 'BILL APPROVAL' ? 'BILL DETAIL' : raw
}

const opsFlatHeaderLabel = (label: string) => label === 'BILL APPROVAL' ? 'BILL DETAIL' : label

const opsVisibleHeader = (base: OpsBase, mode: OpsMode, dept: OpsDept, header: string[]): string[] => {
  const hidden = hiddenOpsColumns(base, mode, dept)
  const visible = header
    .map((label, index) => ({ label: opsHeaderName(base, mode, dept, index, label), index }))
    .filter(({ index }) => !hidden.has(index))
    .map(({ label }) => opsFlatHeaderLabel(label))
  return visible[0] === 'TIME' ? visible.slice() : ['TIME', ...visible]
}

const opsFlatHeader = (header: string[]): string[] => {
  const renamed = header.map(opsFlatHeaderLabel)
  return renamed[0] === 'TIME' ? renamed : ['TIME', ...renamed]
}

// Lookup the mockup header for a (base, mode, dept) leaf.
function rawOpsHeaderFor(base: OpsBase, mode: OpsMode, dept: OpsDept, type?: OpsType | null): string[] {
  // Destination FCD follows the same operational schema as TCD for
  // DAP/DDU/DDP. Keeping one source schema also lets linked TCD rows align
  // field-for-field when they are mirrored into FCD.
  if (dept === 'FCD' && ['DAP', 'DDU', 'DDP'].includes(String(type || '').toUpperCase())) {
    return rawOpsHeaderFor(base, mode, 'TCD', type)
  }
  if (mode === 'FCL' && ['DDU', 'DDP'].includes(String(type || '').toUpperCase()) && dept === 'GSD') {
    const flow = `${String(type).toUpperCase()}+`
    return ['TIME', 'EXTRA SERVICE', 'JOB NO#', 'ICD OPS', 'CLIENT', 'DEALT INFO', 'NOTICE', flow, 'SENT ICD', 'ACTION']
  }
  if (mode === 'FCL' && ['DDU', 'DDP'].includes(String(type || '').toUpperCase()) && dept === 'ICD') {
    const flow = `${String(type).toUpperCase()}+`
    return ['TIME', 'BU', 'DEALT INFO', 'EXTRA SERVICE', 'PAYMENT REQUEST', 'NOTICE', 'SALES', 'JOB NO#', 'ICD OPS', flow, 'CLIENT', 'SHIPPER', 'CNEE', 'ORIGIN AGENT', 'DESTINATION AGENT', 'LINER', 'REF#', 'HBL NO#', 'MBL NO#', 'VOLUME', 'ROUTE', 'VESSEL/VOYAGE', 'ATD', 'ETA', 'PRE-ALERT CONFIRMATION', 'CONT/SEAL INFO', 'DELIVERY DETAIL', 'MANIFEST SUBMIT', 'ARRIVAL NOTICE SENDING', 'ATA', 'DO VALIDITY', 'PICKUP STATUS', 'ACTION']
  }
  if (mode === 'FCL' && ['DDU', 'DDP'].includes(String(type || '').toUpperCase()) && dept === 'CCD') {
    const notice = String(type).toUpperCase() === 'DDU' ? ['NOTICE'] : []
    return ['TIME', 'BU', 'DEALT INFO', 'PAYMENT REQUEST', ...notice, 'SALES', 'ICD OPS', 'CCD OPS', 'CLIENT', 'SHIPPER', 'CNEE', 'LINER', 'REF#', 'HBL NO#', 'MBL NO#', 'VOLUME', 'ROUTE', 'VESSEL/VOYAGE', 'ATD', 'ETA', 'PRE-ALERT CONFIRMATION', 'CONT/SEAL INFO', 'ATA', 'DO VALIDITY', 'CLEARANCE DOCS APPROVAL', 'CLEARANCE DETAIL', 'ACTION']
  }
  if (mode === 'FCL' && ['DDU', 'DDP'].includes(String(type || '').toUpperCase()) && dept === 'TCD') {
    return ['TIME', 'BU', 'DEALT INFO', 'PAYMENT REQUEST', 'NOTICE', 'SALES', 'ICD OPS', 'TCD OPS', 'CLIENT', 'SHIPPER', 'CNEE', 'LINER', 'REF#', 'HBL NO#', 'MBL NO#', 'VOLUME', 'ROUTE', 'VESSEL/VOYAGE', 'ATD', 'ATA', 'DELIVERY DETAIL', 'DO VALIDITY', 'CLEARANCE DETAIL', 'TRUCK & CONT/SEAL INFO', 'ACTION']
  }
  if (mode === 'FCL' && ['DDU', 'DDP'].includes(String(type || '').toUpperCase()) && dept === 'FCD') {
    const flow = `${String(type).toUpperCase()}+`
    return ['TIME', 'BU', 'DEALT INFO', 'EXPENSE/COLLECT LIST', 'NOTICE', 'SALES', 'ICD OPS', flow, 'CLIENT', 'SHIPPER', 'CNEE', 'ORIGIN AGENT', 'DESTINATION AGENT', 'LINER', 'REF#', 'HBL NO#', 'MBL NO#', 'ATD', 'ATA', 'VOLUME', 'ROUTE', 'VESSEL/VOYAGE', 'TRUCK & CONT/SEAL INFO', 'ACTION']
  }
  const effectiveType = ['LCL', 'AIR'].includes(mode) ? type : type === 'DDU' || type === 'DDP' ? 'DUP' : type
  if (mode === 'LCL' && effectiveType) {
    const lcl = LCL_FLAT_COLS[effectiveType]?.[dept]
    if (lcl) return opsFlatHeader(lcl)
  }
  if (mode === 'AIR' && effectiveType) {
    const air = AIR_FLAT_COLS[effectiveType]?.[dept]
    if (air) return opsFlatHeader(air)
  }
  const flat = effectiveType ? FLAT_COLS[effectiveType]?.[dept] : null
  if (flat) return opsFlatHeader(flat)
  if (mode === 'AIR') return opsVisibleHeader(base, mode, dept, AIR_BASE_HEADER)
  if (base === 'EFA') {
    if (dept === 'CCD') return opsVisibleHeader(base, mode, dept, EFA_CCD_HEADER)
    if (dept === 'DCD') return opsVisibleHeader(base, mode, dept, EFA_DCD_HEADER)
    if (dept === 'FCD') return opsVisibleHeader(base, mode, dept, EFA_FCD_HEADER)
    return opsVisibleHeader(base, mode, dept, EFA_BASE_HEADER)
  }
  if (base === 'FCF') {
    if (dept === 'DCD') return opsVisibleHeader(base, mode, dept, FCF_DCD_HEADER)
    if (dept === 'FCD') return opsVisibleHeader(base, mode, dept, FCF_FCD_HEADER)
    return opsVisibleHeader(base, mode, dept, FCF_BASE_HEADER)
  }
  if (base === 'DO') {
    if (dept === 'FCD') return opsVisibleHeader(base, mode, dept, DO_FCD_HEADER)
    return opsVisibleHeader(base, mode, dept, DO_BASE_HEADER)
  }
  if (base === 'DUP' || base === 'D2D') {
    if (dept === 'FCD') return opsVisibleHeader(base, mode, dept, DUP_FCD_HEADER)
    if (mode === 'LCL') {
      if (dept === 'ICD') return opsVisibleHeader(base, mode, dept, DUP_ICD_HEADER_LCL)
      if (dept === 'CCD') return opsVisibleHeader(base, mode, dept, DUP_CCD_HEADER_LCL)
      if (dept === 'TCD') return opsVisibleHeader(base, mode, dept, DUP_TCD_HEADER_LCL)
    }
    if (dept === 'ICD') return opsVisibleHeader(base, mode, dept, DUP_ICD_HEADER_FCL)
    if (dept === 'CCD') return opsVisibleHeader(base, mode, dept, DUP_CCD_HEADER_FCL)
    if (dept === 'TCD') return opsVisibleHeader(base, mode, dept, DUP_TCD_HEADER_FCL)
    return opsVisibleHeader(base, mode, dept, DUP_BASE_HEADER)
  }
  return opsVisibleHeader(base, mode, dept, EFA_BASE_HEADER)
}

export function opsHeaderFor(base: OpsBase, mode: OpsMode, dept: OpsDept, type?: OpsType | null): string[] {
  const rawHeader = rawOpsHeaderFor(base, mode, dept, type)
  const normalizedType = String(type || '').toUpperCase()
  const mirrorsTcdSchema = String(dept || '').toUpperCase() === 'FCD' &&
    ['DAP', 'DDU', 'DDP'].includes(normalizedType)
  // DAP/DDU/DDP use one shared DO INFORMATION form. The date is stored inside
  // DO INFO, so a second DO VALIDITY column must not be generated downstream.
  const visibleHeader = ['DAP', 'DDU', 'DDP'].includes(normalizedType)
    ? rawHeader.map((label) => label === 'DO VALIDITY' ? 'DO INFO' : label)
    : rawHeader
  // Downstream worksheets own one assignee column. GSD additionally shows the
  // next department's linked assignee beside its own GSD column.
  const departmentOpsPattern = /^(?:(?:GSD|ECD|ICD|TCD|CCD|DCD|FCD|QCD) OPS|OPS[12]?)$/
  const firstOpsColumn = visibleHeader.findIndex((label) => departmentOpsPattern.test(String(label).toUpperCase()))
  const header = firstOpsColumn < 0
    ? visibleHeader
    : String(dept).toUpperCase() === 'GSD'
    ? visibleHeader.reduce<string[]>((result, label, index) => {
        if (!departmentOpsPattern.test(String(label).toUpperCase())) return [...result, label]
        if (index !== firstOpsColumn) return result
        const linkedOps = String(label).toUpperCase()
        return linkedOps === 'OPS' || linkedOps === 'GSD OPS'
          ? [...result, 'GSD']
          : [...result, 'GSD', linkedOps]
      }, [])
    : visibleHeader.reduce<string[]>((result, label, index) => {
        if (!departmentOpsPattern.test(String(label).toUpperCase())) return [...result, label]
        return index === firstOpsColumn ? [...result, `${String(dept).toUpperCase()} OPS`] : result
      }, [])
  const deptUpper = String(dept || '').toUpperCase()
  const orderedHeader = deptUpper === 'GSD' && String(type || '').toUpperCase() === 'EXW' && header.includes('EXW+')
    ? (() => {
        const withoutFlow = header.filter((label) => label !== 'EXW+')
        const ecdOpsColumn = withoutFlow.indexOf('ECD OPS')
        const insertAt = ecdOpsColumn >= 0 ? ecdOpsColumn + 1 : withoutFlow.indexOf('GSD') + 1
        return [...withoutFlow.slice(0, insertAt), 'EXW+', ...withoutFlow.slice(insertAt)]
      })()
    : header
  const headerWithJobNo = (['TCD', 'CCD'].includes(deptUpper) || mirrorsTcdSchema) && !orderedHeader.includes('JOB NO#')
    ? (() => {
        const salesColumn = orderedHeader.findIndex((label) => label === 'SALES')
        const insertAt = salesColumn >= 0 ? salesColumn + 1 : Math.max(0, orderedHeader.findIndex((label) => label === 'TIME') + 1)
        return [...orderedHeader.slice(0, insertAt), 'JOB NO#', ...orderedHeader.slice(insertAt)]
      })()
    : orderedHeader
  const headerWithMode = (!['TCD', 'CCD', 'DCD'].includes(deptUpper) && !mirrorsTcdSchema) || headerWithJobNo.includes('MODE')
    ? headerWithJobNo
    : (() => {
        const timeColumn = headerWithJobNo.findIndex((label) => label === 'TIME')
        const insertAt = timeColumn >= 0 ? timeColumn + 1 : 0
        return [...headerWithJobNo.slice(0, insertAt), 'MODE', ...headerWithJobNo.slice(insertAt)]
      })()
  if (headerWithMode.includes('NOTES')) return headerWithMode
  const actionColumn = headerWithMode.lastIndexOf('ACTION')
  const notesAt = actionColumn >= 0 ? actionColumn : headerWithMode.length
  return [...headerWithMode.slice(0, notesAt), 'NOTES', ...headerWithMode.slice(notesAt)]
}

